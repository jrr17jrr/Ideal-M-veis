import type { Product, ProductVariant } from "@/types";

/**
 * Catálogo mockado da loja.
 *
 * ⚠️ Componentes NÃO importam este arquivo — usam `src/services/products.ts`.
 *
 * Coerência garantida: `category` = tipo do móvel · `room` = ambiente ·
 * `variants` = cores com imagens próprias · `options` = tamanho/tecido/etc.
 * Futuro: tabelas `products`, `product_images`, `product_variants`.
 */

/** 2 fotos base por produto: `<slug>.jpg` e `<slug>-2.jpg`. */
function imgs(slug: string): string[] {
  return [
    `/images/products/${slug}.jpg`,
    `/images/products/${slug}-2.jpg`,
  ];
}

/** Helper para variação de cor. */
function variant(
  color: string,
  colorHex: string,
  stock: number,
  images: string[] = [],
  priceAdjustment = 0,
  material?: string,
): ProductVariant {
  return {
    id: `v-${color.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    color,
    colorHex,
    material,
    stock,
    images,
    priceAdjustment,
  };
}

